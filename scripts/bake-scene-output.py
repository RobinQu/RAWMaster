#!/usr/bin/env python3
"""Freeze the ACES 2 display-linear prefix of two official OCIO views (037)."""
import argparse
import hashlib
import importlib.metadata
import json
from pathlib import Path

import numpy as np
import PyOpenColorIO as ocio

CONFIG = 'studio-config-v4.0.0_aces-v2.0_ocio-v2.5'
CONFIG_SHA = '3a48b0421e51d4284ec07187f86b74387321550b65f5a2f237885bf269dbc99e'
VIEWS = {
    'sdr709': ('sRGB - Display', 'ACES 2.0 - SDR 100 nits (Rec.709)', ocio.ExponentWithLinearTransform),
    'hdr2020': ('Rec.2100-PQ - Display', 'ACES 2.0 - HDR 1000 nits (Rec.2020)', ocio.Lut1DTransform),
}
WIDTH = 362
SAMPLES = [[-0.05, 0.125, 0.25], [0, 0, 0], [0.0003, 0.0003, 0.0003], [0.18, 0.18, 0.18],
           [1, 1, 1], [8, 8, 8], [32, 32, 32], [1024, 1024, 1024], [4, 1.5, 0.375], [64, 2, 1],
           [1, 100, 1], [1.5, 2, 64], [0.125, 0, 0], [0, 0.125, 0], [0, 0, 0.125], [-1, -2, -4]]


def generate():
    config = ocio.Config.CreateFromBuiltinConfig(CONFIG)
    if ocio.__version__ != '2.5.0' or hashlib.sha256(config.serialize().encode()).hexdigest() != CONFIG_SHA:
        raise SystemExit('Unsupported OCIO release or ACES configuration')
    package = importlib.metadata.distribution('opencolorio')
    license_path = next(x for x in package.files if str(x).endswith('/licenses/LICENSE'))
    yield 'LICENSE.txt', package.locate_file(license_path).read_bytes()
    reference = {'configSHA256': CONFIG_SHA, 'views': {}}
    for key, (display, view, encoding_type) in VIEWS.items():
        processor = config.getProcessor(ocio.DisplayViewTransform(src='ACEScg', display=display, view=view))
        transforms = list(processor.createGroupTransform())
        if not isinstance(transforms[-1], encoding_type):
            raise SystemExit(f'{key}: expected one final display encoding transform')
        if sum(isinstance(t, ocio.FixedFunctionTransform) and t.getStyle() == ocio.FIXED_FUNCTION_ACES_OUTPUT_TRANSFORM_20
               for t in transforms) != 1:
            raise SystemExit(f'{key}: expected exactly one ACES 2 output transform')
        linear = ocio.GroupTransform()
        for t in transforms[:-1]:
            linear.appendTransform(t)
        prefix = config.getProcessor(linear)
        cpu = prefix.getDefaultCPUProcessor()
        encoded = processor.getDefaultCPUProcessor()
        reference['views'][key] = [dict(scene=p, linear=cpu.applyRGB(list(p)), encoded=encoded.applyRGB(list(p))) for p in SAMPLES]
        shader = ocio.GpuShaderDesc.CreateShaderDesc()
        shader.setLanguage(ocio.GPU_LANGUAGE_MSL_2_0)
        prefix.getDefaultGPUProcessor().extractGpuShaderInfo(shader)
        tables = list(shader.getTextures())
        if len(tables) != 2 or len(list(shader.get3DTextures())) or len(list(shader.getUniforms())):
            raise SystemExit(f'{key}: unsupported shader resource layout')
        for table, channels, suffix, name in zip(tables, [1, 3], ['reach', 'cusp'], ['ocio_reach_m_table_0', 'ocio_gamut_cusp_table_0']):
            if (table.textureName != name or table.width != WIDTH or table.height != 1 or
                    table.interpolation != ocio.INTERP_NEAREST or table.dimensions != ocio.GpuShaderDesc.TEXTURE_1D):
                raise SystemExit(f'{key}: unexpected ACES 2 table contract')
            values = np.asarray(table.getValues(), dtype='<f4').reshape(WIDTH, channels)
            if not np.isfinite(values).all():
                raise SystemExit(f'{key}: non-finite shader data')
            if channels == 3:
                values = np.pad(values, ((0, 0), (0, 1)))  # Metal has no RGB32F texture format.
            yield f'{key}-{suffix}.f32', values.tobytes()
        header = '// Generated by scripts/bake-scene-output.py with OpenColorIO 2.5.0.\n// Copyright Contributors to the OpenColorIO Project. BSD-3-Clause (LICENSE.txt).\n'
        yield f'{key}.metal', (header + shader.getShaderText()).encode()
    yield 'reference.json', (json.dumps(reference, indent=2, allow_nan=False) + '\n').encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('destination', type=Path)
    parser.add_argument('--check', action='store_true', help='Require all generated files to match; do not write.')
    args = parser.parse_args()
    if not args.check:
        args.destination.mkdir(parents=True, exist_ok=False)
    for name, data in generate():
        path = args.destination / name
        if args.check:
            if path.read_bytes() != data:
                raise SystemExit(f'Generated resource differs: {path}')
        else:
            with path.open('xb') as out:
                out.write(data)
        print(hashlib.sha256(data).hexdigest(), name)


if __name__ == '__main__':
    main()
