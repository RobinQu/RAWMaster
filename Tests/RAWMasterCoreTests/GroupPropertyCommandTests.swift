import XCTest
@testable import RAWMasterCore

final class GroupPropertyCommandTests: XCTestCase {
  private var root: URL!
  private var database: URL!
  private var store: LibraryStore!

  override func setUpWithError() throws {
    root = FileManager.default.temporaryDirectory.appendingPathComponent("RAWMasterGroupProperties-" + UUID().uuidString)
    database = root.appendingPathComponent("library.sqlite")
    store = try LibraryStore(databaseURL: database)
    try store.saveProject(ProjectRecord(id: "project", name: "Photos"))
    try store.saveSession(ImportSession(id: "session", projectID: "project", projectName: "Photos", sourcePath: root.appendingPathComponent("originals").path, mode: .reference))
    for id in ["a", "b", "c", "d"] {
      _ = try store.register(AssetRecord(id: id, sessionID: "session", projectID: "project", sourcePath: root.appendingPathComponent("originals/\(id).ARW").path))
    }
  }
  override func tearDownWithError() throws { store = nil; try? FileManager.default.removeItem(at: root) }
  @discardableResult private func perform(_ request: GroupCommandRequest) throws -> GroupCommandRecord {
    try store.commitGroupCommand(store.previewGroupCommand(request))
  }
  private func create(_ ids: [String] = ["a", "b"], locked: Bool = true) throws -> CaptureGroup {
    try perform(.createWithProperties(assetIDs: ids, name: "Original", kind: "延时", locked: locked)).after[0]
  }
  private func group(_ id: String) throws -> CaptureGroup { try XCTUnwrap(store.loadGroups().first { $0.id == id }) }
  private func reopen() throws { store = nil; store = try LibraryStore(databaseURL: database) }
  private func rows() throws -> [[[String]]] {
    try ["groups_data", "membership", "group_domains", "group_commands", "operations"].map { try store.rows("SELECT * FROM \($0) ORDER BY rowid") }
  }

  func testFixedLegacyJSONStillExecutesReopensAndRestoresWithOriginalPayloadShape() throws {
    // These literal historical payloads are deliberately not generated by the current encoder.
    let fixtures = [
      #"{"create":{"assetIDs":["a","b"],"name":"Legacy","kind":"连拍"}}"#,
      #"{"rename":{"groupID":"old-id","name":"Renamed"}}"#,
      #"{"setKind":{"groupID":"old-id","kind":"HDR"}}"#,
      #"{"setLocked":{"groupID":"old-id","locked":false}}"#,
      #"{"removeMembers":{"groupID":"old-id","assetIDs":["a"]}}"#,
      #"{"reorder":{"groupID":"old-id","assetIDs":["b","a"]}}"#,
      #"{"setParticipation":{"groupIDs":["old-id"],"assetIDs":["a"],"included":false}}"#,
      #"{"merge":{"groupIDs":["one","two"],"name":"Merged","kind":"HDR"}}"#,
      #"{"split":{"groupID":"old-id","movedAssetIDs":["a"],"newName":"Part","newKind":"延时"}}"#,
      #"{"restore":{"commandID":"old-command"}}"#,
    ]
    for fixture in fixtures {
      let data = Data(fixture.utf8)
      let decoded = try JSONDecoder().decode(GroupCommandRequest.self, from: data)
      XCTAssertEqual(try JSONSerialization.jsonObject(with: JSONEncoder().encode(decoded)) as? NSDictionary,
                     try JSONSerialization.jsonObject(with: data) as? NSDictionary)
    }
    let old = try JSONDecoder().decode(GroupCommandRequest.self, from: Data(fixtures[0].utf8))
    let command = try perform(old)
    XCTAssertTrue(command.after[0].locked, "Old create keeps its historical protected default")
    try reopen()
    let persisted = try XCTUnwrap(store.loadGroupCommand(id: command.id))
    guard case .create(let ids, let name, let kind) = persisted.request else { return XCTFail("Old create case must remain durable") }
    XCTAssertEqual(ids, ["a", "b"]); XCTAssertEqual(name, "Legacy"); XCTAssertEqual(kind, "连拍")
    _ = try store.undoGroupCommand(id: command.id)
    try reopen(); XCTAssertTrue(try store.loadGroups().isEmpty)
  }

  func testCreateUsesExplicitPropertiesIncludingUnlockedAndTrimsText() throws {
    let command = try perform(.createWithProperties(assetIDs: ["b", "a"], name: "  Sunset  ", kind: "  校准  ", locked: false))
    let created = command.after[0]
    XCTAssertEqual(created.name, "Sunset"); XCTAssertEqual(created.kind, "校准"); XCTAssertFalse(created.locked)
    XCTAssertEqual(created.assetIDs, ["b", "a"]); XCTAssertEqual(created.includedAssetIDs, ["b", "a"])
    try reopen(); XCTAssertFalse(try group(created.id).locked)
    _ = try store.undoGroupCommand(id: command.id); XCTAssertTrue(try store.loadGroups().isEmpty)
  }

  func testAllPropertiesSaveAsOneDurableCommandAndUndoTogetherWithoutRewritingMembers() throws {
    let original = try create()
    _ = try perform(.setParticipation(groupIDs: [original.id], assetIDs: ["b"], included: false))
    let beforeCount = try store.loadGroupCommands().count
    let command = try perform(.updateProperties(groupID: original.id, name: "Edited", kind: "HDR", locked: false))
    XCTAssertEqual(try store.loadGroupCommands().count, beforeCount + 1)
    let edited = try group(original.id)
    XCTAssertEqual(edited.name, "Edited"); XCTAssertEqual(edited.kind, "HDR"); XCTAssertFalse(edited.locked)
    XCTAssertEqual(edited.id, original.id); XCTAssertEqual(edited.projectID, original.projectID); XCTAssertEqual(edited.origin, original.origin)
    XCTAssertEqual(edited.assetIDs, original.assetIDs); XCTAssertEqual(edited.includedAssetIDs, ["a"])
    try reopen()
    XCTAssertFalse(try group(original.id).locked)
    _ = try store.undoGroupCommand(id: command.id)
    let restored = try group(original.id)
    XCTAssertEqual(restored.name, original.name); XCTAssertEqual(restored.kind, original.kind); XCTAssertTrue(restored.locked)
    XCTAssertEqual(restored.assetIDs, original.assetIDs); XCTAssertEqual(restored.includedAssetIDs, ["a"])
    try reopen(); XCTAssertEqual(try group(original.id).name, original.name)
  }

  func testUpdateGuardsEvenUnchangedDisplayedPropertiesAndRejectsConcurrentEdits() throws {
    for field in ["name", "kind", "lock"] {
      let original = try create()
      let preview = try store.previewGroupCommand(.updateProperties(groupID: original.id, name: "Saved", kind: original.kind, locked: original.locked))
      XCTAssertEqual(Set(preview.dependencies.map(\.domain)), [.existence, .name, .kind, .lock])
      switch field {
      case "name": _ = try perform(.rename(groupID: original.id, name: "Concurrent"))
      case "kind": _ = try perform(.setKind(groupID: original.id, kind: "星空"))
      default: _ = try perform(.setLocked(groupID: original.id, locked: false))
      }
      let before = try rows()
      XCTAssertThrowsError(try store.commitGroupCommand(preview)); XCTAssertEqual(try rows(), before)
    }
  }

  func testPropertiesCommitAndUndoPreserveAnIndependentMemberChangeAfterPreview() throws {
    let original = try create()
    let preview = try store.previewGroupCommand(.updateProperties(groupID: original.id, name: "Saved", kind: "HDR", locked: false))
    _ = try perform(.setParticipation(groupIDs: [original.id], assetIDs: ["b"], included: false))
    let command = try store.commitGroupCommand(preview)
    XCTAssertEqual(try group(original.id).includedAssetIDs, ["a"])
    _ = try store.undoGroupCommand(id: command.id)
    XCTAssertEqual(try group(original.id).includedAssetIDs, ["a"])
    XCTAssertEqual(try group(original.id).name, original.name)
  }

  func testEmptyGroupCanUpdateOnlyItsPropertiesAndNoopNeverWritesHistory() throws {
    let original = try create()
    _ = try perform(.removeMembers(groupID: original.id, assetIDs: original.assetIDs))
    let edited = try perform(.updateProperties(groupID: original.id, name: "Empty", kind: "校准", locked: false))
    XCTAssertTrue(try group(original.id).assetIDs.isEmpty); XCTAssertFalse(try group(original.id).locked)
    let before = try rows()
    XCTAssertThrowsError(try store.previewGroupCommand(.updateProperties(groupID: original.id, name: "Empty", kind: "校准", locked: false)))
    XCTAssertEqual(try rows(), before)
    _ = try store.undoGroupCommand(id: edited.id)
    XCTAssertEqual(try group(original.id).name, original.name); XCTAssertTrue(try group(original.id).assetIDs.isEmpty)
  }

  func testPropertyFailureRollsBackAllThreeFieldsAndNoPartialHistory() throws {
    let original = try create()
    let preview = try store.previewGroupCommand(.updateProperties(groupID: original.id, name: "Edited", kind: "HDR", locked: false))
    let before = try rows()
    try store.exec("CREATE TEMP TRIGGER properties_failure BEFORE INSERT ON group_commands BEGIN SELECT RAISE(ABORT,'injected'); END")
    XCTAssertThrowsError(try store.commitGroupCommand(preview)); XCTAssertEqual(try rows(), before)
    try store.exec("DROP TRIGGER properties_failure")
    _ = try store.commitGroupCommand(preview); XCTAssertFalse(try group(original.id).locked)
  }

  func testAppendNewMembersInRequestOrderPreservesExistingExcludedAndOtherGroupsThenRestores() throws {
    let original = try create(["b", "a"])
    let other = try create(["c", "d"])
    _ = try perform(.setParticipation(groupIDs: [original.id], assetIDs: ["b"], included: false))
    _ = try perform(.setLocked(groupID: original.id, locked: false))
    let preview = try store.previewGroupCommand(.addMembers(groupID: original.id, assetIDs: ["b", "d", "c"]))
    XCTAssertTrue(preview.dependencies.contains { $0.domain == .all })
    XCTAssertFalse(preview.warnings.isEmpty, "Automatic structural protection is visible")
    let command = try store.commitGroupCommand(preview)
    let changed = try group(original.id)
    XCTAssertEqual(changed.assetIDs, ["b", "a", "d", "c"]); XCTAssertEqual(changed.includedAssetIDs, ["a", "d", "c"]); XCTAssertTrue(changed.locked)
    XCTAssertEqual(try group(other.id).assetIDs, other.assetIDs)
    try reopen()
    _ = try store.undoGroupCommand(id: command.id)
    let restored = try group(original.id)
    XCTAssertEqual(restored.assetIDs, ["b", "a"]); XCTAssertEqual(restored.includedAssetIDs, ["a"]); XCTAssertFalse(restored.locked)
    XCTAssertFalse(FileManager.default.fileExists(atPath: root.appendingPathComponent("originals").path), "Group commands never open or write original files")
  }

  func testAppendRejectsEmptyDuplicatesAllExistingCrossProjectAndMissingWithoutWrites() throws {
    let original = try create(locked: false)
    try store.saveProject(ProjectRecord(id: "other", name: "Other"))
    try store.saveSession(ImportSession(id: "foreign-session", projectID: "other", projectName: "Other", sourcePath: root.appendingPathComponent("other").path, mode: .reference))
    _ = try store.register(AssetRecord(id: "foreign", sessionID: "foreign-session", projectID: "other", sourcePath: root.appendingPathComponent("other/f.ARW").path))
    let before = try rows()
    for ids in [[], ["c", "c"], ["b", "a"], ["c", "missing"], ["c", "foreign"]] {
      XCTAssertThrowsError(try store.previewGroupCommand(.addMembers(groupID: original.id, assetIDs: ids)))
      XCTAssertEqual(try rows(), before)
    }
    XCTAssertFalse(try group(original.id).locked, "Adding only existing members cannot silently lock a group")
    XCTAssertThrowsError(try store.previewGroupCommand(.createWithProperties(assetIDs: ["a", "foreign"], name: "Mixed", kind: "HDR", locked: false)))
    XCTAssertThrowsError(try store.previewGroupCommand(.createWithProperties(assetIDs: [], name: "Empty", kind: "HDR", locked: false)))
  }

  func testAppendPreviewGuardsConcurrentTailOrderAndPropertyChanges() throws {
    for change in ["append", "reorder", "name"] {
      let original = try create()
      let preview = try store.previewGroupCommand(.addMembers(groupID: original.id, assetIDs: ["c"]))
      switch change {
      case "append": _ = try perform(.addMembers(groupID: original.id, assetIDs: ["d"]))
      case "reorder": _ = try perform(.reorder(groupID: original.id, assetIDs: ["b", "a"]))
      default: _ = try perform(.rename(groupID: original.id, name: "Concurrent"))
      }
      let before = try rows()
      XCTAssertThrowsError(try store.commitGroupCommand(preview)); XCTAssertEqual(try rows(), before)
    }
  }
}
